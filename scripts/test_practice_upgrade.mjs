// node scripts/test_practice_upgrade.mjs /path/to/@electric-sql/pglite/dist/index.js
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const baseSQL = await readFile(new URL('../content/import-a1-topics-20.sql', import.meta.url), 'utf8');
const upgradeSQL = await readFile(new URL('../content/upgrade-a1-practice-v2.sql', import.meta.url), 'utf8');
const library = JSON.parse(await readFile(new URL('../src/data/practicePacks.json', import.meta.url), 'utf8'));
assert.equal(library.lessons.length, 21);
for (const lesson of library.lessons) {
  assert.equal(lesson.sentences.length, 30);
  assert.equal(new Set(lesson.sentences.map(s => s.english)).size, 30);
  assert(lesson.sentences.every(s => s.vietnamese && s.ipa && s.pronunciation_focus));
  assert.deepEqual(lesson.sentences.map(s => s.position), Array.from({ length: 30 }, (_, i) => i + 1));
  assert.equal(lesson.conversations.length, 3);
  assert(lesson.conversations.every(c => c.turns.length >= 4 && c.turns.every(t => t.length === 3 && t.every(Boolean))));
}
async function db() {
  const instance = new PGlite();
  await instance.exec(`
    CREATE TABLE courses (id bigint PRIMARY KEY, title text);
    INSERT INTO courses VALUES (1,'EnglishwithMikey – Basic Communication A1');
    CREATE TABLE lessons (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      course_id bigint, title text, description text, content text, objectives text,
      order_index integer, lesson_order integer, status text
    );
    CREATE TABLE sentences (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      lesson_id bigint REFERENCES lessons(id), english text, vietnamese text,
      order_index integer, sentence_order integer, ipa text, vocabulary_notes text,
      grammar_explanation text, context_of_use text, audio_url text
    );
    CREATE TABLE learning_progress (user_id text, lesson_id bigint, is_completed boolean, score integer);
    INSERT INTO lessons (course_id,title,description,status) VALUES
      (1,'Lesson 1: Introducing Yourself','Original 1','Published'),
      (1,'Lesson 2: Talking About Your Daily Routine','Original 2','Published');
    INSERT INTO sentences (lesson_id,english,vietnamese,sentence_order) VALUES (1,'Original','Gốc',1);
    INSERT INTO learning_progress VALUES ('student',1,true,100);
  `);
  return instance;
}
const upgraded = await db();
await upgraded.exec(baseSQL);
await upgraded.exec("UPDATE lessons SET status='Published' WHERE id=3; UPDATE sentences SET audio_url='https://example.com/teacher-audio.mp3' WHERE id=2; INSERT INTO learning_progress VALUES ('student',3,true,80);");
const oldRows = (await upgraded.query('SELECT * FROM sentences ORDER BY id')).rows;
const oldProgress = (await upgraded.query('SELECT * FROM learning_progress ORDER BY lesson_id')).rows;
const originalLessons = (await upgraded.query('SELECT * FROM lessons ORDER BY id')).rows;
await upgraded.exec(upgradeSQL);
assert.equal((await upgraded.query('SELECT count(*)::int AS n FROM sentences')).rows[0].n, 601);
for (const row of oldRows) assert.deepEqual((await upgraded.query('SELECT * FROM sentences WHERE id=$1', [row.id])).rows[0], row);
assert.deepEqual((await upgraded.query('SELECT * FROM lessons ORDER BY id')).rows, originalLessons);
assert.deepEqual((await upgraded.query('SELECT * FROM learning_progress ORDER BY lesson_id')).rows, oldProgress);
const counts = (await upgraded.query('SELECT lesson_id,count(*)::int AS n,max(sentence_order) AS last FROM sentences WHERE lesson_id>2 GROUP BY lesson_id')).rows;
assert.equal(counts.length, 20); assert(counts.every(r => r.n === 30 && r.last === 30));
const beforeRerun = (await upgraded.query('SELECT * FROM sentences ORDER BY id')).rows;
await upgraded.exec(upgradeSQL);
assert.deepEqual((await upgraded.query('SELECT * FROM sentences ORDER BY id')).rows, beforeRerun);
await upgraded.close();

const fresh = await db();
await fresh.exec(upgradeSQL);
assert.equal((await fresh.query('SELECT count(*)::int AS n FROM lessons')).rows[0].n, 22);
assert.equal((await fresh.query('SELECT count(*)::int AS n FROM sentences')).rows[0].n, 601);
await fresh.close();

const edited = await db();
await edited.exec(baseSQL);
await edited.exec("UPDATE sentences SET english='Teacher edited sentence' WHERE lesson_id=13;");
const snapshot = (await edited.query('SELECT * FROM sentences ORDER BY id')).rows;
await assert.rejects(edited.exec(upgradeSQL));
await edited.exec('ROLLBACK');
assert.deepEqual((await edited.query('SELECT * FROM sentences ORDER BY id')).rows, snapshot);
await edited.close();
console.log('PASS: 630 unique-per-lesson prompts, 63 dialogues; SQL fresh install, 200→600 upgrade, preserved IDs/audio/status/progress, rerun and atomic rollback on teacher edits.');
