// Usage: node scripts/test_topic_import.mjs /path/to/@electric-sql/pglite/dist/index.js
// The engine is isolated tooling; this script never connects to Supabase.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const sql = await readFile(new URL('../content/import-a1-topics-20.sql', import.meta.url), 'utf8');

async function database({ full = true, wrongCourse = false, conflict = false } = {}) {
  const db = new PGlite();
  await db.exec(`
    CREATE TABLE courses (id bigint PRIMARY KEY, title text);
    INSERT INTO courses VALUES (1, '${wrongCourse ? 'Unrelated course' : 'EnglishwithMikey – Basic Communication A1'}');
    CREATE TABLE lessons (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      course_id bigint REFERENCES courses(id), title text, description text,
      content text, objectives text, order_index integer, status text
      ${full ? ', lesson_order integer' : ''}
    );
    CREATE TABLE sentences (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      lesson_id bigint REFERENCES lessons(id), english text, vietnamese text,
      order_index integer
      ${full ? ', sentence_order integer, vocabulary_notes text, grammar_explanation text, context_of_use text' : ''}
    );
    INSERT INTO lessons (course_id, title, description, order_index, status)
    VALUES (1, 'Lesson 1: Introducing Yourself', 'Keep original 1', 1, 'Published'),
           (1, 'Lesson 2: Talking About Your Daily Routine', 'Keep original 2', 2, 'Published');
    INSERT INTO sentences (lesson_id, english, vietnamese, order_index)
    VALUES (1, 'Original sentence', 'Câu gốc', 1);
  `);
  if (conflict) await db.exec(`INSERT INTO lessons (course_id,title,description) VALUES (1,'Lesson 13: The Weather','Unrelated content');`);
  return db;
}

for (const full of [true, false]) {
  const db = await database({ full });
  const original = (await db.query('SELECT * FROM lessons WHERE id IN (1,2) ORDER BY id')).rows;
  await db.exec(sql);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM lessons')).rows[0].n, 22);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM sentences')).rows[0].n, 201);
  assert.deepEqual((await db.query('SELECT * FROM lessons WHERE id IN (1,2) ORDER BY id')).rows, original);
  const added = (await db.query("SELECT * FROM lessons WHERE description LIKE '%mikey-a1-topics-v1%' ORDER BY order_index")).rows;
  assert.deepEqual(added.map(l => l.order_index), Array.from({ length: 20 }, (_, i) => i + 3));
  assert(added.every(l => l.status === 'Draft'));
  if (full) assert.deepEqual(added.map(l => l.lesson_order), added.map(l => l.order_index));
  const counts = (await db.query('SELECT lesson_id, count(*)::int AS n, min(order_index) AS first, max(order_index) AS last FROM sentences WHERE lesson_id > 2 GROUP BY lesson_id')).rows;
  assert.equal(counts.length, 20);
  assert(counts.every(r => r.n === 10 && r.first === 1 && r.last === 10));
  if (full) assert.equal((await db.query('SELECT count(*)::int AS n FROM sentences WHERE sentence_order <> order_index')).rows[0].n, 0);
  await db.exec("UPDATE lessons SET status='Published', content='Teacher edit' WHERE order_index=3;");
  const beforeRerun = (await db.query('SELECT * FROM lessons ORDER BY id')).rows;
  await db.exec(sql);
  assert.deepEqual((await db.query('SELECT * FROM lessons ORDER BY id')).rows, beforeRerun);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM sentences')).rows[0].n, 201);
  await db.close();
}

for (const options of [{ wrongCourse: true }, { conflict: true }]) {
  const db = await database(options);
  const before = (await db.query('SELECT * FROM lessons ORDER BY id')).rows;
  await assert.rejects(db.exec(sql));
  await db.exec('ROLLBACK');
  assert.deepEqual((await db.query('SELECT * FROM lessons ORDER BY id')).rows, before);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM sentences')).rows[0].n, 1);
  await db.close();
}
console.log('PASS: full/minimal schemas, 20 lessons/200 sentences, ordering, original preservation, safe rerun, course guard and atomic rollback on title conflict.');

// Formatting variants are the same verified course, not a different target.
for (const title of [
  'EnglishwithMikey – Basic Communication A1  ',
  'ENGLISHWITHMIKEY — BASIC COMMUNICATION A1',
  'EnglishwithMikey\u00a0–\u00a0Basic Communication A1',
]) {
  const db = await database();
  await db.query('UPDATE courses SET title=$1 WHERE id=1', [title]);
  await db.exec(sql);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM lessons')).rows[0].n, 22);
  await db.close();
}
console.log('PASS: course title case, trailing whitespace, and non-breaking spaces.');
